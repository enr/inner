// ── Log file ──────────────────────────────────────────────────────────────────

func TestLauncher_logFile_created(t *testing.T) {
	l := &Launcher{Stdin: bytes.NewReader(nil), Stdout: io.Discard, Stderr: io.Discard}
	logDir := t.TempDir()

	result, err := l.Run(exec.Command("sh", "-c", "echo log-line"), RunOptions{
		LogDir: logDir,
		RunID:  "testrun-001",
	})
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if result.LogPath == "" {
		t.Fatal("expected LogPath to be set")
	}
	data, err := os.ReadFile(result.LogPath)
	if err != nil {
		t.Fatalf("reading log: %v", err)
	}
	if !strings.Contains(string(data), "log-line") {
		t.Errorf("expected log to contain 'log-line', got: %q", string(data))
	}
}

